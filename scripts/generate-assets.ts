// Generates the asset kit from its sources: the ghost in src/identity/ghost.ts, the handle in
// identity/whatsaaaa.json and one file per project in identity/projects/.
//
//   node scripts/generate-assets.ts           writes assets/
//   node scripts/generate-assets.ts --check   fails when assets/ is not what the sources produce
import { readFileSync, readdirSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import { parseArgs } from 'node:util'
import { GHOST, GHOST_POSES } from '../src/identity/ghost.ts'
import { type Identity, type KitFile, buildKit, readProject, writeKit } from './lib/kit.ts'

const root = resolve(import.meta.dirname, '..')

function readIdentities(): Identity[] {
  const handle = JSON.parse(readFileSync(join(root, 'identity/whatsaaaa.json'), 'utf8'))
  const projects = readdirSync(join(root, 'identity/projects'))
    .filter((file) => file.endsWith('.json'))
    .sort()
    .map((file) => readProject(join(root, 'identity/projects', file)))
  return [{ ...handle, kind: 'ghost', sprite: GHOST, poses: GHOST_POSES }, ...projects]
}

/** The index of a kit, for people and tools that want to know what is in it. */
function manifest(files: KitFile[]): string {
  const identities: Record<string, object[]> = {}
  for (const { path, use, width, height } of files) {
    const [identity, file] = path.split('/') as [string, string]
    ;(identities[identity] ??= []).push({ file, width, height, use })
  }
  return (
    JSON.stringify(
      { note: 'Generated by scripts/generate-assets.ts from identity/. Do not edit.', identities },
      null,
      2,
    ) + '\n'
  )
}

function listFiles(dir: string): string[] {
  try {
    return readdirSync(dir, { recursive: true, withFileTypes: true })
      .filter((entry) => entry.isFile())
      .map((entry) => relative(dir, join(entry.parentPath, entry.name)))
      .sort()
  } catch {
    return []
  }
}

const { values } = parseArgs({ options: { check: { type: 'boolean', default: false } } })

const out = join(root, 'assets')
const files = (await Promise.all(readIdentities().map(buildKit))).flat()
const kit = new Map<string, string | Buffer>(files.map((file) => [file.path, file.content]))
kit.set('manifest.json', manifest(files))

if (values.check) {
  const onDisk = listFiles(out)
  const problems = [
    ...[...kit.keys()].filter((file) => !onDisk.includes(file)).map((file) => `missing: ${file}`),
    ...onDisk.filter((file) => !kit.has(file)).map((file) => `not generated: ${file}`),
    ...onDisk
      .filter(
        (file) =>
          kit.has(file) && !Buffer.from(kit.get(file)!).equals(readFileSync(join(out, file))),
      )
      .map((file) => `out of date: ${file}`),
  ]
  if (problems.length > 0) {
    console.error(
      `assets/ does not match identity/ and the tokens. Run "pnpm assets".\n${problems.join('\n')}`,
    )
    process.exit(1)
  }
  console.log(`assets/ is up to date (${kit.size} files)`)
} else {
  writeKit(out, kit)
  console.log(`wrote ${kit.size} files to ${relative(process.cwd(), out) || '.'}`)
}
